export function fatiaListaCurriculo({ excluir = [], cursor = 0, limite = 10 } = {}) {
  const bloqueados = new Set(
    (Array.isArray(excluir) ? excluir : [])
      .map((n) => String(n || "").replace(/\D/g, "").slice(-11))
      .filter(Boolean),
  );
  const empresas = [];
  let i = Math.max(0, Number(cursor) || 0);
  const max = Math.min(Math.max(Number(limite) || 10, 1), 20);
  while (i < LISTA_EMPRESAS_CURRICULO.length && empresas.length < max) {
    const item = LISTA_EMPRESAS_CURRICULO[i];
    i += 1;
    if (!item) continue;
    const cel = item.whatsapp;
    if (!cel || bloqueados.has(cel) || bloqueados.has(`55${cel}`)) continue;
    bloqueados.add(cel);
    empresas.push({
      id: `curriculo-${cel}`,
      nome: item.nome,
      whatsapp: cel,
      whatsappOk: true,
      cidade: "São Paulo",
      bairro: "",
      endereco: "",
      categoria: item.categoria || "Empresa de Software",
      site: item.site || "",
      origem: "base_curriculo",
    });
  }
  return {
    empresas,
    cursor: i,
    restantes: Math.max(0, LISTA_EMPRESAS_CURRICULO.length - i),
    total: LISTA_EMPRESAS_CURRICULO.length,
    esgotada: i >= LISTA_EMPRESAS_CURRICULO.length,
  };
}
